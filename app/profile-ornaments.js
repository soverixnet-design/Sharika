/* Sharika profile showcase and extracted headwear catalog.
   Source: user-supplied 17748.mp4, seven separate transparent PNGs.
   No fictional friends/supporters are generated by this module. */
(function () {
  "use strict";
  var ASSET = "./profile-headwear/";
  var ITEMS = [
    {id:"sh-vip", name:"VIP Gold", file:"vip-gold.png", role:"vip"},
    {id:"sh-seller", name:"Coin Seller", file:"coin-seller.png", role:"seller"},
    {id:"sh-ruby", name:"Ruby Heart", file:"ruby-heart.png"},
    {id:"sh-sapphire", name:"Sapphire", file:"sapphire-crystal.png"},
    {id:"sh-rainbow", name:"Rainbow", file:"rainbow-floral.png"},
    {id:"sh-welcome", name:"Golden Welcome", file:"golden-welcome.png"},
    {id:"sh-shadow", name:"Shadow Crown", file:"shadow-crown.png"}
  ];
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return {"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c];
    });
  }
  function authorized(item) {
    if (!item.role) return true;
    // Privileged badges are preview-only until a server-verified grant is supplied.
    // Server APIs must independently enforce cosmetic grants before persisting them.
    var verified = window.SharikaVerifiedFrameEntitlements;
    return !!(verified && verified.source === "server" && verified[item.role] === true);
  }
  function imageOf(item) { return ASSET + item.file; }
  var oldFRL = window.FRL;
  if (typeof oldFRL === "function") {
    window.FRL = function () {
      var out = oldFRL();
      if (!Array.isArray(out)) out = [];
      out = out.slice();
      var settings = null;
      try { settings = typeof ADM === "function" ? ADM() : null; } catch (e) {}
      var configured = settings && settings.t && Array.isArray(settings.t.fr) ? settings.t.fr : [];
      ITEMS.forEach(function (item) {
        if (!authorized(item)) return;
        var stored = configured.find(function (row) { return row && row.st === item.id; });
        if (stored && stored.on === false) return;
        var existing = out.find(function (row) { return row[0] === item.id; });
        if (existing) {
          if (!existing[3]) existing[3] = imageOf(item);
        } else {
          out.push([item.id, stored && stored.n || item.name, "", imageOf(item)]);
        }
      });
      return out;
    };
  }
  function memberList(v) { return Array.isArray(v) ? v.filter(function (p) {return p && typeof p === "object";}) : []; }
  function person(p) {
    var name = esc(p.name || p.n || "Member"), photo = p.photo || p.avatar || p.pic;
    var icon = typeof photo === "string" && /^(https:\/\/|data:image\/(?:png|jpeg|webp);base64,)/i.test(photo)
      ? '<img src="' + esc(photo) + '" alt="" loading="lazy">' : '<span>👤</span>';
    return '<div class="sh-person"><div class="sh-person-avatar">' + icon + '</div><small>' + name + '</small></div>';
  }
  function titleLine(name, count) {
    return '<div class="sh-section-title"><h3>' + name + '</h3>' + (count ? '<span>' + count + '</span>' : '') + '</div>';
  }
  function renderCollection() {
    var active = window.A && window.A.frameImg || "";
    var choices = ITEMS.map(function (item) {
      var can = authorized(item), selected = active === imageOf(item);
      return '<button type="button" class="sh-frame-choice' + (selected ? ' selected' : '') +
        '" data-sh-frame="' + esc(item.id) + '"' + (can ? '' : ' disabled aria-disabled="true"') +
        ' aria-label="' + esc(item.name + (can ? ", apply frame" : ", role required")) + '">' +
        '<span class="sh-frpreview"><span class="sh-frface">👤</span><img class="sh-frimg" src="' +
        imageOf(item) + '" alt="" loading="lazy"></span>' +
        '<span class="sh-frname">' + esc(item.name) + '</span>' +
        '<small>' + (selected ? 'Equipped ✓' : can ? 'Tap to equip' : '🔒 Role required') + '</small></button>';
    }).join("");
    return '<section class="sh-collection" aria-label="Profile collections">' +
      '<div class="sh-collection-tabs" role="tablist" aria-label="Collection type">' +
      ['Gift','Medal','Vehicle','Headwear','Impression'].map(function (name) {
        var key = name.toLowerCase();
        return '<button type="button" role="tab" data-sh-tab="' + key + '" aria-selected="' +
          (key === 'headwear' ? 'true' : 'false') + '" class="' + (key === 'headwear' ? 'on' : '') +
          '">' + name + '</button>';
      }).join("") + '</div>' +
      '<div class="sh-tab-panel" data-sh-panel="headwear">' +
      '<p class="sh-tiny">Seven separate frames from your reference video. Frames gently glow and float.</p>' +
      '<div class="sh-frame-grid">' + choices + '</div></div>' +
      '<div class="sh-tab-panel" data-sh-panel="gift" hidden>Gift history is available in the Gift tab of the profile.</div>' +
      '<div class="sh-tab-panel" data-sh-panel="medal" hidden>Earned medals are shown in the Badges section of the profile.</div>' +
      '<div class="sh-tab-panel" data-sh-panel="vehicle" hidden>No vehicle decorations have been synced to this profile.</div>' +
      '<div class="sh-tab-panel" data-sh-panel="impression" hidden>No impressions have been synced to this profile.</div>' +
      '</section>';
  }
  function sections(m) {
    var friends = memberList(m && m.friendList);
    var supporters = memberList(m && m.topSupporters);
    var partner = m && m.cpPartner && typeof m.cpPartner === "object" ? m.cpPartner : null;
    var honors = Array.isArray(m && m.honorTitles) ? m.honorTitles : [];
    var shownTitles = honors.filter(function (v) { return typeof v === "string"; }).slice(0,4).map(function (v) {
      return '<span class="sh-honor">' + esc(v) + '</span>';
    }).join("");
    return '<div class="sh-showcase">' +
      '<section class="sh-honor-section">' + titleLine('Honor Title') +
      '<div class="sh-honor-strip">' + (shownTitles || '<span class="sh-muted">No honor title equipped</span>') + '</div></section>' +
      '<section>' + titleLine('CP') + '<div class="sh-gold-panel sh-cp-panel">' +
      '<div class="sh-ring sh-ring-red">' + (partner ? person(partner) : '<span class="sh-question">?</span>') + '</div>' +
      '<div class="sh-heart-mark">💗<small>' + (partner ? 'CP Partner' : 'Not linked') + '</small></div>' +
      '<div class="sh-ring sh-ring-red"><span class="sh-question">♡</span></div></div></section>' +
      '<section>' + titleLine('Friends', friends.length ? String(friends.length) : '') +
      '<div class="sh-gold-panel sh-friends-panel">' +
      (friends.length ? friends.slice(0,4).map(person).join("") :
      '<span class="sh-muted">Friends will appear here when profile data is available.</span>') +
      '</div></section>' +
      '<section>' + titleLine('Supporters') + '<div class="sh-support-grid">' +
      (supporters.length ? supporters.slice(0,3).map(function (p,i) {
        return '<div class="sh-support-card"><b>TOP ' + (i+1) + '</b>' + person(p) + '</div>';
      }).join("") : [1,2,3].map(function (n) {
        return '<div class="sh-support-card empty"><b>TOP ' + n + '</b><span>—</span><small>No data yet</small></div>';
      }).join("")) + '</div></section>' + renderCollection() + '</div>';
  }
  function cover(m) {
    var src = m && m.cover;
    var safe = typeof src === "string" && (/^data:image\/(?:png|jpeg|webp);base64,/i.test(src) || /^https:\/\//i.test(src));
    return '<div class="sh-profile-cover"' + (safe ? ' style="background-image:url(&quot;' + esc(src) + '&quot;)"' : '') +
      '><span>✦ SHARIKA ✦</span></div>';
  }
  var oldPfHTML = window.pfHTML;
  if (typeof oldPfHTML === "function") {
    window.pfHTML = function (m,mine) {
      var html = oldPfHTML(m,mine), marker = '<div class="tabs">';
      return html.indexOf(marker) >= 0 ? html.replace(marker, sections(m) + marker) : html + sections(m);
    };
  }
  var oldMeHTML = window.meHTML;
  if (typeof oldMeHTML === "function") {
    window.meHTML = function (m) {
      var html = oldMeHTML(m);
      html = html.replace('<div class="mav">', cover(m) + '<div class="mav">');
      html = html.replace('<div class="tiles">', sections(m) + '<div class="tiles">');
      return html;
    };
  }
  var oldPfWire = window.pfWire;
  if (typeof oldPfWire === "function") {
    window.pfWire = function (root,m,mine) {
      oldPfWire(root,m,mine);
      root.querySelectorAll("[data-sh-tab]").forEach(function (btn) {
        btn.onclick = function () {
          var key = btn.getAttribute("data-sh-tab"), wrap = btn.closest(".sh-collection");
          wrap.querySelectorAll("[data-sh-tab]").forEach(function (tab) {
            var selected = tab === btn;
            tab.classList.toggle("on",selected);
            tab.setAttribute("aria-selected", selected ? "true" : "false");
          });
          wrap.querySelectorAll("[data-sh-panel]").forEach(function (panel) {
            panel.hidden = panel.getAttribute("data-sh-panel") !== key;
          });
        };
      });
      if (!mine) return;
      root.querySelectorAll("[data-sh-frame]:not([disabled])").forEach(function (btn) {
        btn.onclick = function () {
          var id = btn.getAttribute("data-sh-frame");
          var item = ITEMS.find(function (row) {return row.id === id;});
          if (!item || !authorized(item) || !window.A) return;
          A.frame = item.id;
          A.frameImg = imageOf(item);
          if (typeof saveA === "function") saveA();
          if (typeof renderMe === "function") renderMe();
          if (root.id === "pfc") {
            root.innerHTML = pfHTML(m,true);
            pfWire(root,m,true);
          }
          if (typeof toast === "function") toast(item.name + " frame equipped ✓");
        };
      });
    };
  }
})();
